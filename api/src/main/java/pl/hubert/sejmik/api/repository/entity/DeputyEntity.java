package pl.hubert.sejmik.api.repository.entity;

import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import pl.hubert.sejmik.domain.model.Faction;

/**
 * One deputy of one game ({@code deputies} table).
 */
@Entity
@Table(name = "deputies")
public class DeputyEntity {

    /** Technical primary key generated by the database; {@code deputyId} is the in-game number (1-20). */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /** The owning side of the relationship: the {@code game_id} foreign key column. LAZY: load on demand. */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "game_id")
    private GameEntity game;

    private int deputyId;
    private String name;
    private String coatOfArms;

    /** STRING stores "ROYAL"; the default ORDINAL would store 0 and break when enum constants are reordered. */
    @Enumerated(EnumType.STRING)
    private Faction faction;

    private int loyaltyToKing;
    private double corruptibility;
    private int kingBribes;
    private int magnateBribes;

    protected DeputyEntity() {
    }

    public DeputyEntity(int deputyId, String name, String coatOfArms, Faction faction,
                        int loyaltyToKing, double corruptibility) {
        this.deputyId = deputyId;
        this.name = name;
        this.coatOfArms = coatOfArms;
        this.faction = faction;
        this.loyaltyToKing = loyaltyToKing;
        this.corruptibility = corruptibility;
    }

    void setGame(GameEntity game) {
        this.game = game;
    }

    public int getDeputyId() {
        return deputyId;
    }

    public String getName() {
        return name;
    }

    public String getCoatOfArms() {
        return coatOfArms;
    }

    public Faction getFaction() {
        return faction;
    }

    public int getLoyaltyToKing() {
        return loyaltyToKing;
    }

    public double getCorruptibility() {
        return corruptibility;
    }

    public int getKingBribes() {
        return kingBribes;
    }

    public int getMagnateBribes() {
        return magnateBribes;
    }

    public void setBribes(int kingBribes, int magnateBribes) {
        this.kingBribes = kingBribes;
        this.magnateBribes = magnateBribes;
    }
}
